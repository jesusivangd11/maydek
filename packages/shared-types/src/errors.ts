  RATE_LIMITED: 'RATE_LIMITED',
  CASH_SESSION_REQUIRED: 'CASH_SESSION_REQUIRED',
  CASH_SESSION_ALREADY_OPEN: 'CASH_SESSION_ALREADY_OPEN',
  PERIOD_CLOSED: 'PERIOD_CLOSED',
  PRICE_MISMATCH: 'PRICE_MISMATCH',
